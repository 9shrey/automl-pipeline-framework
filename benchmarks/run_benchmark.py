"""Run a deterministic, CI-friendly AutoML benchmark.

The scheduled GitHub Action should be a health check for the framework, not a
network reliability test. The benchmark therefore uses small sklearn datasets
that are always available after project installation and writes a markdown
leaderboard for humans to inspect.
"""

from __future__ import annotations

import argparse
import time
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.datasets import load_breast_cancer, load_iris, load_wine, make_classification
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score
from sklearn.model_selection import train_test_split
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from automl.api import AutoMLClassifier
from automl.config.loader import load_config_from_path


@dataclass(frozen=True)
class BenchmarkDataset:
    name: str
    X: pd.DataFrame
    y: np.ndarray


def _load_dataset(name: str, seed: int) -> BenchmarkDataset:
    loaders = {
        "iris": load_iris,
        "wine": load_wine,
        "breast_w": load_breast_cancer,
    }
    if name in loaders:
        bunch = loaders[name](as_frame=True)
        return BenchmarkDataset(name=name, X=bunch.data, y=np.asarray(bunch.target))

    X_arr, y = make_classification(
        n_samples=240,
        n_features=10,
        n_informative=6,
        n_redundant=1,
        random_state=seed,
    )
    columns = [f"f{i}" for i in range(X_arr.shape[1])]
    return BenchmarkDataset(name=name, X=pd.DataFrame(X_arr, columns=columns), y=y)


def _baseline_score(X_train: pd.DataFrame, X_test: pd.DataFrame, y_train: np.ndarray, y_test: np.ndarray) -> float:
    model = make_pipeline(
        StandardScaler(),
        LogisticRegression(max_iter=500, random_state=0),
    )
    model.fit(X_train, y_train)
    return float(accuracy_score(y_test, model.predict(X_test)))


def _benchmark_dataset(dataset: BenchmarkDataset, *, config_path: Path, seed: int) -> dict[str, object]:
    X_train, X_test, y_train, y_test = train_test_split(
        dataset.X,
        dataset.y,
        test_size=0.25,
        random_state=seed,
        stratify=dataset.y,
    )

    cfg = load_config_from_path(config_path)
    cfg = cfg.model_copy(update={"n_trials": min(cfg.n_trials, 8), "time_budget_seconds": 60})
    cfg.search.space.models[:] = [m for m in cfg.search.space.models if m in {"logreg", "histgb"}]
    cfg.search.space.feature_selection[:] = ["none"]
    cfg.ensembling.enabled = False
    cfg.ensembling.strategy = "none"
    cfg.run.out_dir = str(Path("runs") / "benchmarks" / dataset.name)

    t0 = time.perf_counter()
    automl = AutoMLClassifier(config=cfg, metric="accuracy")
    automl.fit(X_train, y_train)
    wall = time.perf_counter() - t0

    pred = automl.predict(X_test)
    automl_score = float(accuracy_score(y_test, pred))
    baseline = _baseline_score(X_train, X_test, y_train, y_test)

    return {
        "dataset": dataset.name,
        "task": "classification",
        "automl_score": automl_score,
        "baseline_score": baseline,
        "delta": automl_score - baseline,
        "best_model": automl.leaderboard_.iloc[0]["model"],
        "trials": len(automl.leaderboard_),
        "wall_seconds": wall,
    }


def _write_markdown(rows: list[dict[str, object]], out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Benchmark Leaderboard",
        "",
        "_Auto-generated by `python benchmarks/run_benchmark.py --config configs/fast.yaml`._",
        "",
        "| Dataset | Task | AutoML | Baseline (logistic regression) | Delta | Best model | Trials | Seconds |",
        "|---|---|---:|---:|---:|---|---:|---:|",
    ]
    for row in rows:
        lines.append(
            "| {dataset} | {task} | {automl_score:.4f} | {baseline_score:.4f} | "
            "{delta:+.4f} | {best_model} | {trials} | {wall_seconds:.1f} |".format(**row)
        )
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run the fast AutoML benchmark.")
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--out", type=Path, default=Path("benchmarks/leaderboard.md"))
    parser.add_argument("--datasets", nargs="*", default=["iris", "wine", "breast_w"])
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    cfg = load_config_from_path(args.config)
    rows = [
        _benchmark_dataset(_load_dataset(name, cfg.seed), config_path=args.config, seed=cfg.seed)
        for name in args.datasets
    ]
    _write_markdown(rows, args.out)
    print(f"wrote {args.out} ({len(rows)} datasets)")


if __name__ == "__main__":
    main()
